-- Fleet Management — Admin Allowlist
-- Run this script on the Oracle application schema.
-- This table controls which employees can access the admin dashboard.
-- ============================================================

CREATE TABLE FLEET_ADMIN_ALLOWLIST (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMP_NO     VARCHAR2(50 CHAR)  NOT NULL,
    LABEL      VARCHAR2(255 CHAR) NULL,
    ADDED_BY   VARCHAR2(255 CHAR) NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX faa_emp_no_uq ON FLEET_ADMIN_ALLOWLIST (EMP_NO);

