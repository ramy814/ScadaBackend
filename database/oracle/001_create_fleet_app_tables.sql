-- Fleet Management application tables for Oracle 12c/19c+.
-- Run this inside the application schema only if PHP oci8 is not available
-- and you cannot run: php artisan migrate --database=oracle
--
-- Existing municipality source tables are intentionally not modified:
-- VEHICLE and BENEFICIARIES are read-only integration sources.

CREATE TABLE sessions (
    id VARCHAR2(255 CHAR) PRIMARY KEY,
    user_id NUMBER NULL,
    ip_address VARCHAR2(45 CHAR) NULL,
    user_agent CLOB NULL,
    payload CLOB NOT NULL,
    last_activity NUMBER(10) NOT NULL
);

CREATE INDEX sess_user_id_idx ON sessions (user_id);
CREATE INDEX sess_last_act_idx ON sessions (last_activity);

CREATE TABLE cache (
    key VARCHAR2(255 CHAR) PRIMARY KEY,
    value CLOB NOT NULL,
    expiration NUMBER(10) NOT NULL
);

CREATE TABLE cache_locks (
    key VARCHAR2(255 CHAR) PRIMARY KEY,
    owner VARCHAR2(255 CHAR) NOT NULL,
    expiration NUMBER(10) NOT NULL
);

CREATE TABLE jobs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue VARCHAR2(255 CHAR) NOT NULL,
    payload CLOB NOT NULL,
    attempts NUMBER(3) NOT NULL,
    reserved_at NUMBER(10) NULL,
    available_at NUMBER(10) NOT NULL,
    created_at NUMBER(10) NOT NULL
);

CREATE INDEX jobs_queue_index ON jobs (queue);

CREATE TABLE job_batches (
    id VARCHAR2(255 CHAR) PRIMARY KEY,
    name VARCHAR2(255 CHAR) NOT NULL,
    total_jobs NUMBER(10) NOT NULL,
    pending_jobs NUMBER(10) NOT NULL,
    failed_jobs NUMBER(10) NOT NULL,
    failed_job_ids CLOB NOT NULL,
    options CLOB NULL,
    cancelled_at NUMBER(10) NULL,
    created_at NUMBER(10) NOT NULL,
    finished_at NUMBER(10) NULL
);

CREATE TABLE failed_jobs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR2(255 CHAR) NOT NULL,
    connection CLOB NOT NULL,
    queue CLOB NOT NULL,
    payload CLOB NOT NULL,
    exception CLOB NOT NULL,
    failed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX fj_uuid_uq ON failed_jobs (uuid);

CREATE TABLE personal_access_tokens (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tokenable_type VARCHAR2(255 CHAR) NOT NULL,
    tokenable_id VARCHAR2(255 CHAR) NOT NULL,
    name CLOB NOT NULL,
    token VARCHAR2(64 CHAR) NOT NULL,
    abilities CLOB NULL,
    last_used_at TIMESTAMP NULL,
    expires_at TIMESTAMP NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL
);

CREATE UNIQUE INDEX pat_token_uq ON personal_access_tokens (token);
CREATE INDEX pat_tokenable_idx ON personal_access_tokens (tokenable_type, tokenable_id);
CREATE INDEX pat_expires_idx ON personal_access_tokens (expires_at);

CREATE TABLE sms_login_codes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR2(255 CHAR) NOT NULL,
    code_hash VARCHAR2(255 CHAR) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    consumed_at TIMESTAMP NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL
);

CREATE INDEX sms_phone_idx ON sms_login_codes (phone);

CREATE TABLE trips (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id VARCHAR2(36 CHAR) NOT NULL,
    oracle_driver_id VARCHAR2(255 CHAR) NOT NULL,
    driver_name VARCHAR2(255 CHAR) NOT NULL,
    driver_phone VARCHAR2(255 CHAR) NULL,
    driver_employee_number VARCHAR2(255 CHAR) NULL,
    oracle_vehicle_id VARCHAR2(255 CHAR) NULL,
    vehicle_plate VARCHAR2(255 CHAR) NOT NULL,
    vehicle_name VARCHAR2(255 CHAR) NULL,
    vehicle_type VARCHAR2(255 CHAR) NULL,
    status VARCHAR2(255 CHAR) DEFAULT 'uploaded' NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP NULL,
    origin_type VARCHAR2(255 CHAR) DEFAULT 'free_text' NOT NULL,
    origin_id VARCHAR2(255 CHAR) NULL,
    origin_text VARCHAR2(255 CHAR) NOT NULL,
    destination_type VARCHAR2(255 CHAR) DEFAULT 'free_text' NOT NULL,
    destination_id VARCHAR2(255 CHAR) NULL,
    destination_text VARCHAR2(255 CHAR) NOT NULL,
    mission_type VARCHAR2(255 CHAR) NULL,
    notes CLOB NULL,
    start_odometer NUMBER(10) NULL,
    end_odometer NUMBER(10) NULL,
    points_expected NUMBER(10) DEFAULT 0 NOT NULL,
    points_received NUMBER(10) DEFAULT 0 NOT NULL,
    client_checksum VARCHAR2(255 CHAR) NULL,
    server_checksum VARCHAR2(255 CHAR) NULL,
    confirmed_at TIMESTAMP NULL,
    virtual_fuel_liters NUMBER(10, 3) NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL
);

CREATE UNIQUE INDEX trips_local_id_uq ON trips (local_id);
CREATE INDEX trips_oracle_driver_idx ON trips (oracle_driver_id);
CREATE INDEX trips_oracle_vehicle_idx ON trips (oracle_vehicle_id);
CREATE INDEX trips_vehicle_plate_idx ON trips (vehicle_plate);
CREATE INDEX trips_status_idx ON trips (status);

CREATE TABLE trip_points (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id NUMBER NOT NULL,
    sequence_number NUMBER(10) NOT NULL,
    latitude NUMBER(10, 7) NOT NULL,
    longitude NUMBER(10, 7) NOT NULL,
    accuracy NUMBER(8, 2) NULL,
    speed NUMBER(8, 2) NULL,
    heading NUMBER(8, 2) NULL,
    battery_level NUMBER(3) NULL,
    provider VARCHAR2(255 CHAR) NULL,
    captured_at TIMESTAMP NOT NULL,
    CONSTRAINT trip_points_trip_fk FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE
);

CREATE INDEX tp_captured_at_idx ON trip_points (captured_at);
CREATE UNIQUE INDEX tp_trip_seq_uq ON trip_points (trip_id, sequence_number);

CREATE TABLE trip_stops (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id NUMBER NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP NULL,
    reason VARCHAR2(255 CHAR) NULL,
    notes CLOB NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    CONSTRAINT trip_stops_trip_fk FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE
);

CREATE TABLE trip_passengers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id NUMBER NOT NULL,
    employee_id VARCHAR2(255 CHAR) NULL,
    name VARCHAR2(255 CHAR) NOT NULL,
    source VARCHAR2(255 CHAR) DEFAULT 'free_text' NOT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    CONSTRAINT trip_passengers_trip_fk FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE
);

CREATE INDEX tpass_emp_id_idx ON trip_passengers (employee_id);

